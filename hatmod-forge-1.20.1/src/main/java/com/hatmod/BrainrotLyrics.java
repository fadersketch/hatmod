    private static Line[] shift(Line[] source) {
        Line[] out = new Line[source.length];
        for (int i = 0; i < source.length; i++) {
            out[i] = new Line(source[i].tick() - LRC_OFFSET_TICKS, source[i].text());
        }
        return out;
    }

    /**
     * 这一句最多挂多久（刻）。间奏里人声停了、下一句还早，歌词不能一直亮在屏幕上；
     * 4.5 秒也刚好让「拔け出せない」在 NOPE 弹出之前收掉，不会两行叠在一起。
     */
    private static final int MAX_LINE_TICKS = 90;

    private BrainrotLyrics() {
    }

    public static int count() {
        return LINES.length;
    }

    public static int tickAt(int index) {
        return LINES[index].tick();
    }

    public static String textAt(int index) {
        return LINES[index].text();
    }

    /**
     * 这一句每个字的起唱时刻与时长（打包值 {@code ((偏移 + CUE_BIAS) << 8) | 时长刻}），
     * 见 {@link #CUE}；起唱刻 = 本行 {@link #tickAt(int)} + 偏移。
     */
    public static int[] cue(int index) {
        return CUE[index];
    }

    /**
     * 这一句显示到哪一刻为止：下一句的起点，最多 4.5 秒；最后一句按 3 秒算。
     *
     * <p>但不能早于**最后一个字唱完**——「抜け出せない」的「い」要拖将近两秒，
     * 按 90 刻一刀切会在长音中间把整行收掉（扫字忽然停在一半）。
     */
    public static int endTick(int index) {
        int start = LINES[index].tick();
        int natural = index + 1 < LINES.length ? LINES[index + 1].tick() : start + 60;
        int cueEnd = start;
        for (int packed : CUE[index]) {
            int from = start + (packed >>> 8) - CUE_BIAS;
            cueEnd = Math.max(cueEnd, from + Math.max(1, packed & 0xFF));
        }
        return Math.max(Math.min(natural, start + MAX_LINE_TICKS), cueEnd);
    }

    /** 这一刻正在唱第几句：取「起点不晚于 {@code age}」的最后一句；还没开唱返回 -1。 */
    public static int currentIndex(int age) {
        int found = -1;
        for (int i = 0; i < LINES.length; i++) {
            if (LINES[i].tick() > age) {
                break;
            }
            found = i;
        }
        return found;
    }
